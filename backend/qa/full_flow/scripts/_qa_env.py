_KEY_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def _unquote(value: str) -> str:
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
        quote = value[0]
        inner = value[1:-1]
        if quote == '"':
            inner = (
                inner.replace("\\n", "\n")
                .replace("\\r", "\r")
                .replace("\\t", "\t")
                .replace('\\"', '"')
                .replace("\\\\", "\\")
            )
        return inner
    # Strip an unquoted trailing comment only when preceded by whitespace.
    return re.split(r"\s+#", value, maxsplit=1)[0].strip()


def parse_env(path: Path) -> dict[str, str]:
    if not path.exists():
        return {}
    values: dict[str, str] = {}
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#"):
            continue
        if line.startswith("export "):
            line = line[len("export ") :].strip()
        if "=" not in line:
            continue
        key, value = line.split("=", 1)
        key = key.strip()
        if not _KEY_RE.match(key):
            continue
        values[key] = _unquote(value)
    return values


def _quote(value: str) -> str:
    if value == "":
        return "''"
    if "'" not in value:
        return f"'{value}'"
    escaped = value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")
    return f'"{escaped}"'


def write_env(path: Path, values: dict[str, str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    lines = [ENV_HEADER.rstrip(), ""]
    for key in sorted(values):
        lines.append(f"{key}={_quote(values[key])}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    path.chmod(0o600)


def load_qa_env(*, require: bool = True) -> dict[str, str]:
    values = parse_env(ENV_FILE)
    if not values and require:
        raise SystemExit(f"missing {ENV_FILE}; run `./backend/qa/full_flow/qa.sh init` first")
    # Existing process environment wins, so CI can override any value.
    for key, value in os.environ.items():
        if key.startswith(("QA_", "APP_", "SESSION_", "OIDC_", "JENKINS_", "GITHUB_")):
            values[key] = value
    return values


def require_keys(values: dict[str, str], keys: tuple[str, ...] | list[str]) -> list[str]:
    return [key for key in keys if not values.get(key, "").strip()]


def replace_database(url: str, database: str) -> str:
    """Return ``url`` pointing at another database, preserving credentials."""
    parts = urlsplit(url)
    if not parts.scheme.startswith("postgresql"):
        raise SystemExit("DATABASE_URL must use the postgresql scheme")
    return urlunsplit((parts.scheme, parts.netloc, f"/{database}", parts.query, parts.fragment))


def database_name(url: str) -> str:
    return urlsplit(url).path.lstrip("/") or "postgres"


def asyncpg_dsn(url: str) -> str:
    return url.replace("postgresql+asyncpg://", "postgresql://", 1)


def admin_dsn(url: str) -> str:
    return replace_database(asyncpg_dsn(url), "postgres")


def random_secret(nbytes: int = 24) -> str:
    return secrets.token_urlsafe(nbytes)


